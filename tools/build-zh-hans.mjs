// Builds assets/i18n/zh-Hans.js from the Traditional Chinese text in the site's pages.
// Usage (from this folder):  npm install  &&  npm run build:zh-hans
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parse } from "node-html-parser";
import * as OpenCC from "opencc-js";

const PAGES = ["index.html", "two-messiahs.html"];

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const toCN = OpenCC.Converter({ from: "tw", to: "cn" });

// Mainland conventions on top of the character conversion
const fixups = [
  [/「/g, "“"], [/」/g, "”"], [/『/g, "‘"], [/』/g, "’"],
  [/西元/g, "公元"], [/・/g, "·"],
];
const convert = (s) => fixups.reduce((t, [re, to]) => t.replace(re, to), toCN(s));

// Collect every Traditional string; a key shared by both pages must have the same text
const source = {};
const where = {};
function add(key, text, page) {
  if (key in source && source[key] !== text) {
    console.warn(`! "${key}" differs between ${where[key]} and ${page}; using ${where[key]}`);
    return;
  }
  source[key] = text;
  where[key] = page;
}
for (const page of PAGES) {
  const html = parse(readFileSync(join(root, page), "utf8"));
  for (const el of html.querySelectorAll("[data-i18n]")) {
    add(el.getAttribute("data-i18n"), el.innerHTML.trim(), page);
  }
  for (const el of html.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of el.getAttribute("data-i18n-attr").split(";")) {
      const i = pair.indexOf(":");
      add(pair.slice(i + 1).trim(), el.getAttribute(pair.slice(0, i).trim()) ?? "", page);
    }
  }
}

const dict = {};
for (const [key, text] of Object.entries(source)) dict[key] = convert(text);
// Hand-tuned entries that differ from a straight conversion
dict["ed.zh.script"] = "繁体中文";

const out =
  "// Generated by tools/build-zh-hans.mjs from " + PAGES.join(" and ") + ". Do not edit by hand.\n" +
  "window.LAMALO_I18N = window.LAMALO_I18N || {};\n" +
  'window.LAMALO_I18N["zh-Hans"] = ' + JSON.stringify(dict, null, 2) + ";\n";
writeFileSync(join(root, "assets/i18n/zh-Hans.js"), out, "utf8");
console.log(`zh-Hans.js written with ${Object.keys(dict).length} keys`);
